// render-ledger.mjs — the ledger is JSON (ledger.json); this renders the Markdown
// view (components-programme.md) from it. Never edit the Markdown by hand.
// Usage: node docs/plan/render-ledger.mjs            renders components-programme.md
//        node docs/plan/render-ledger.mjs --rehash   rewrites every slot's scopeHash
//        (a deliberate scope change: add the dated changes line, then rehash)
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';

const here = path.dirname(new URL(import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, '$1'));
const src = path.join(here, 'ledger.json');
const out = path.join(here, 'components-programme.md');
const L = JSON.parse(fs.readFileSync(src, 'utf8'));

/** The first 12 hex characters of the SHA-256 of the scope text; the test recomputes it. */
export const scopeHash = scope => crypto.createHash('sha256').update(String(scope)).digest('hex').slice(0, 12);

if (process.argv.includes('--rehash')) {
  for (const s of L.slots) s.scopeHash = scopeHash(s.scope);
  fs.writeFileSync(src, JSON.stringify(L, null, 1) + '\n');
  console.log(`${L.slots.length} slots rehashed → ${src}`);
}

const esc = s => String(s ?? '').replace(/\|/g, '\|').replace(/\r?\n/g, ' ');
const lines = [];
lines.push(`# ${L.title}`, '', '_Generated from `ledger.json` by `render-ledger.mjs`. Do not edit this file; edit the JSON and re-render._', '', L.preamble, '');
lines.push('## Rules the ledger enforces', '');
L.rules.forEach((r, i) => lines.push(`${i + 1}. ${r}`));
lines.push('', "## Changes to the plan (dated, with the operator's word)", '', '| Date | Change | Word |', '|---|---|---|');
for (const c of L.changes) lines.push(`| ${c.date} | ${esc(c.change)} | ${esc(c.word)} |`);
const phases = [...new Set(L.slots.map(s => s.phase))];
for (const ph of phases) {
  const meta = L.phases[ph] ?? { title: ph, note: '' };
  lines.push('', `## ${meta.title}`, '');
  if (meta.note) lines.push(meta.note, '');
  lines.push('| Slot | Scope | Decision scan | Acceptance | Status · evidence |', '|---|---|---|---|---|');
  for (const s of L.slots.filter(s => s.phase === ph)) {
    const scan = [`Fixed by: ${esc(s.fixedBy)}`, s.defaults ? `Defaults: ${esc(s.defaults)}` : '', s.needsWord ? `**Needs your word:** ${esc(s.needsWord)}` : 'Needs your word: none'].filter(Boolean).join(' · ');
    const pages = s.pages?.length ? ` · serves ${s.pages.join(', ')}` : '';
    const ev = s.status === 'done' ? `done · ${esc(s.evidence)}${pages}` : s.status === 'started' ? `started${s.evidence ? ` · ${esc(s.evidence)}` : ''}` : 'planned';
    lines.push(`| **${s.id}** ${esc(s.title)} | ${esc(s.scope)} | ${scan} | ${esc(s.acceptance)} | ${ev} |`);
  }
}
const open = L.slots.filter(s => s.needsWord && s.status !== 'done').length;
lines.push('', `_${L.slots.length} slots · ${L.slots.filter(s => s.status === 'done').length} done · ${open} carry a question for the operator._`, '');
fs.writeFileSync(out, lines.join('\n'));
console.log(`${L.slots.length} slots → ${out}`);
